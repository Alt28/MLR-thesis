"""Build explicitly synthetic UI demonstration workbooks, never research evidence."""
from pathlib import Path
import random
import pandas as pd


def prepare():
    destination = Path(__file__).resolve().parents[1] / 'frontend/public/assets/datasets'
    destination.mkdir(parents=True, exist_ok=True)
    for mode, seed in [('Bus', 103), ('Train', 207)]:
        rng = random.Random(seed)
        rows = []
        for i in range(180):
            traffic, weather, period = rng.randrange(3), rng.randrange(3), rng.randrange(3)
            passengers, distance, frequency = rng.randint(25, 450), rng.choice([5, 9, 14, 20, 27, 35]), rng.randint(4, 24)
            # An arbitrary software fixture formula, not an empirical transport model.
            wait = max(1, 8 + .025 * passengers + .22 * distance - .35 * frequency
                       + 2.5 * traffic + 1.5 * weather + period + .5 * traffic * weather + rng.uniform(-3, 3))
            rows.append({'Record ID': f'DEMO-{mode.upper()}-{i+1:03}',
                         'Traffic Condition': ['Light', 'Moderate', 'Heavy'][traffic],
                         'Weather Condition': ['Clear', 'Cloudy', 'Rain'][weather],
                         'Passenger Volume': passengers, 'Route Distance': distance,
                         'Vehicle Frequency': frequency, 'Time of Day': ['Morning', 'Afternoon', 'Evening'][period],
                         'Actual Waiting Time': round(wait, 2), 'Transport Mode': mode,
                         'Station': 'Fictional demo station', 'Route': f'Fictional route {distance}',
                         'Data Source': 'SYNTHETIC / DEMO - software testing only'})
        with pd.ExcelWriter(destination / f'transit_{mode.lower()}_SYNTHETIC_DEMO.xlsx') as writer:
            pd.DataFrame(rows).to_excel(writer, sheet_name='Observations', index=False)
            pd.DataFrame([
                ['Data source', '', 'SYNTHETIC / DEMO. Dataset is simulated. Only for software testing; not final thesis evidence.'],
                ['Vehicle Frequency', 'vehicles/hour', 'Simulated service-event rate, not fleet availability.'],
                ['Route Distance', 'km', 'Simulated route length.'],
                ['Passenger Volume', 'passengers', 'Simulated count for a preceding 60-minute window.'],
                ['Actual Waiting Time', 'minutes', 'Artificial target generated by scripts/prepare_demo_library.py.'],
                ['Traffic Condition', 'category', 'Artificial category for exercising the schema, including in the train fixture; no claim of rail relevance.'],
                ['Generation', '', f'Deterministic seed {seed}; 180 fictional observations; no real location, operator, or passenger records.'],
            ], columns=['Variable', 'Unit', 'Definition']).to_excel(writer, sheet_name='Sources_Methodology', index=False)
        print(f'Prepared {mode}: {len(rows)} synthetic observations')


if __name__ == '__main__':
    prepare()
